test_that("bohr_cis() rejects bad input", {
  s <- paste0("S", 1:30)
  ph <- matrix(stats::runif(60), 2, 30, dimnames = list(c("P1", "P2"), s))
  G <- matrix(stats::rbinom(90, 2, 0.4), 3, 30, dimnames = list(c("v1", "v2", "v3"), s))
  V <- data.frame(id = rownames(G), chr = "1", pos = c(100, 200, 300))
  Pr <- data.frame(id = c("P1", "P2"), chr = "1", pos = c(150, 250))
  expect_error(bohr_cis(unname(ph), G, V, Pr), "row names")
  ph2 <- ph; colnames(ph2) <- NULL; expect_error(bohr_cis(ph2, G, V, Pr), "column names")
  ph3 <- ph; ph3[1, 1] <- 2; expect_error(bohr_cis(ph3, G, V, Pr), "\\[0, 1\\]")
  G2 <- G; G2[1, 1] <- 0.5; expect_error(bohr_cis(ph, G2, V, Pr), "dosages")
  G3 <- G[, -1]; expect_error(bohr_cis(ph, G3, V, Pr), "no column")
  expect_error(bohr_cis(ph, G, V[, c("id", "chr")], Pr), "chr and pos")
  expect_error(bohr_cis(ph, G, V[1:2, ], Pr), "no entry")
  expect_error(bohr_cis(ph, G, V, Pr[1, ]), "no row")
  expect_error(bohr_cis(ph, G, V, Pr, window = -1), "window")
  expect_error(bohr_cis(ph, G, V, Pr, chromosomes = "chr9"), "No promoter")
  expect_error(bohr_cis(ph, G, V, Pr, covariates = matrix(1, 5, 2)), "one row per sample|no row")
  expect_error(bohr_cis(ph, G, V, Pr, boundary_share = c(0.9, 0.1)), "boundary_share")
  expect_error(bohr_cis(ph, G, V, Pr, fdr = 2), "fdr")
  expect_error(bohr_cis(ph, G, V, Pr, ncores = 0), "ncores")
  expect_error(bohr_cis(ph, G, V, Pr, major_score = 1:2), "major_score")
  V2 <- V; V2$end <- V2$pos - 1; expect_error(bohr_cis(ph, G, V2, Pr), "end >= pos")
})

test_that("utilities reject bad input", {
  expect_error(acat(c(0.5, 1.5)), "\\[0, 1\\]")
  expect_error(acat(c(-1, 0.1), log = TRUE), "<= 0")
  expect_error(acat("a"), "numeric")
  expect_error(simes(c(0.1, 2)), "\\[0, 1\\]")
  expect_error(bb_select(c(0.1, NA), c("a", "b")), "missing")
  expect_error(bb_select(c(0.1, 0.2), "a"), "group")
  expect_error(bb_select(c(0.1, 0.2), c("a", "b"), alpha = 1), "alpha")
  expect_error(simulate_bohr(0), "n")
  expect_error(simulate_bohr(10, freq = 0), "freq")
  expect_error(simulate_bohr(10, sigma = 1), "sigma")
  expect_error(simulate_bohr(10, p0 = 0.6, p1 = 0.5), "sum to less than 1")
  expect_error(simulate_bohr(10, mu = 0.9, effect_mu = 0.1, x = rep(2, 10)), "mu")
  expect_error(simulate_bohr(10, x = c(1, NA)), "finite")
  expect_error(mirror_pairs(matrix(0.5, 2, 3, dimnames = list(c("a", "b"), 1:3)), group = "g"), "one value per feature")
})
