## Input validation.

test_that("bohr_fit() and bohr_test() reject bad input", {
  y <- c(rep(0, 10), seq(0.1, 0.9, length.out = 30), rep(1, 10))
  expect_error(bohr_fit("a"), "numeric")
  expect_error(bohr_fit(c(y, 1.2)), "\\[0, 1\\]")
  expect_error(bohr_fit(c(y, -0.1)), "\\[0, 1\\]")
  expect_error(bohr_fit(y, covariates = matrix(1:4, 2)), "one row per element")
  Z <- matrix(stats::rnorm(100), 50); Z[3, 1] <- NA
  expect_error(bohr_fit(y, covariates = Z), "missing")
  expect_error(bohr_fit(y, covariates = cbind(1, matrix(stats::rnorm(50), 50))), "constant column")
  expect_error(bohr_fit(y, covariates = data.frame(a = letters[1:50])), "numeric")
  expect_error(bohr_fit(y, control = list(maxit = 10)), "bohr_control")
  expect_error(bohr_test(y, x = 1:3), "one value")
  expect_error(bohr_test(y, x = letters[1:50]), "numeric")
  expect_error(bohr_test(y, x = c(Inf, rep(0, 49))), "infinite")
  expect_error(bohr_test(y, x = rep(0:2, length.out = 50), fit = list()), "bohr_fit")
  f <- bohr_fit(y)
  expect_error(bohr_test(rev(y), rep(0:2, length.out = 50), fit = f), "does not match")
  X <- cbind(a = rep(0:2, length.out = 50), b = c(NA, rep(1:2, length.out = 49)))
  expect_error(bohr_test(y, X, fit = f), "missing values")
  expect_error(bohr_test(y, rep(0:2, length.out = 50), all_stats = NA), "TRUE or FALSE")
  expect_error(bohr_test(y, rep(0:2, length.out = 50), type = "ordinal"), "should be one of")
  expect_error(bohr_test(y, rep(0:2, length.out = 50), contrast = c(1, 1)), "contrast")
  expect_error(bohr_test(y, rep(0:2, length.out = 50), contrast = 1), "contrast")
})

test_that("bohr_test() handles constant, missing and skipped predictors gracefully", {
  y <- c(rep(0, 10), seq(0.1, 0.9, length.out = 30), rep(1, 10))
  r <- bohr_test(y, rep(1, 50))
  expect_match(r$error, "constant")
  expect_true(is.na(r$log_p_mu))
  x <- rep(0:2, length.out = 50); x[c(2, 5)] <- NA
  r <- bohr_test(y, x)
  expect_identical(r$n, 48L)
  r <- bohr_test(rep(0, 50), rep(0:2, length.out = 50))
  expect_match(r$error, "skipped")
})

